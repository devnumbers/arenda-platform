/**
 * Модель страницы-каталога срезов «Платежи объекта»/«Автоплатежи объекта»
 * (#463; сплит — решение владельца #1071): списки «Платежи» показывают
 * только ручные правила — автоплатежи живут в своём срезе, секции главного
 * экрана и карточка объекта уже делят так же. Разделение клиентское —
 * канон проекта (бекенд отдаёт все правила, серверный фильтр не вводим).
 */

import type { Payment } from '@/entities/payment';

/** Срезы каталога с правилами; третий вариант экрана ('overdue') идёт мимо
 * этой модели — у него другой список (операции, не правила). */
export type CatalogRulesVariant = 'payments' | 'auto';

/** Правила одного среза каталога: 'payments' — ручные (не автоплатежи),
 * 'auto' — автоплатежи. Порядок входа сохраняется — сортировку по
 * ближайшему вхождению каталог делает снаружи. */
export function catalogRules(
  payments: ReadonlyArray<Payment>,
  variant: CatalogRulesVariant,
): ReadonlyArray<Payment> {
  return payments.filter((payment) =>
    variant === 'auto' ? payment.autoPay : !payment.autoPay,
  );
}
