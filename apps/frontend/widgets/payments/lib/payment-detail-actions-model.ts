import type { Payment } from '@/entities/payment';

/**
 * Состав круглых действий экрана платежа (#818): «Оплатить» живёт, пока есть
 * неоплаченные месяцы (см. ниже — settled заменяет слот); «Изменить» и пауза
 * скрываются у управляемого платежа (isRentalManaged — платёж аренды правится
 * только через аренду, мутации правила дают 409), вместо «Изменить» у
 * незавершённой аренды живёт «Изменить аренду» (#1158): условия правятся
 * на экране аренды. Завершённое правило живёт без паузы (история 44 спеки
 * #453) — по клиентскому предикату endedRule: серверный isCompleted у
 * бессрочной паузы уже «завершен» (ничего больше не материализует), а
 * пауза на экране остаётся возобновляемой.
 *
 * Вычисляемая завершённость (#1341): при settled (серверный isCompleted —
 * глоссарий «Завершённый платёж») «Оплатить» заменяется на «Завершить» —
 * оплаты больше нечего отмечать. Состав не реагирует на открытую паузу и
 * не знает о гейтах мутации: ревизия 2 #1426 сняла серверные гейты (дата
 * окончания, «всё оплачено», пауза — доступность как у удаления), а
 * приглашение владелец оставил как есть («эта кнопка уже есть, новые не
 * добавляй»): слот оплаты у паузного правила по-прежнему не заменяется —
 * состав экрана не менялся, а мутация теперь принимает любое состояние
 * правила.
 *
 * Управляемый платёж (решение владельца 22.10): при settled — все месяцы
 * аренды оплачены («Ожидает действия») — disabled «Оплатить» не оставляем,
 * вместо него «Завершить аренду» (completeRental): вход в стандартный
 * мастер завершения аренды через итоги (макет 1550:93718 — круглая кнопка
 * страницы аренды). Решает серверная завершённость: клиентский предикат
 * (endDate прошла) при живом долге «Оплатить» сохраняет. Аренда уже
 * завершена (isRentalCompleted) — ряд пуст вовсе: завершать нечего, слота
 * «Оплатить» у платежа завершённой аренды больше нет (раньше там висела
 * disabled «Оплатить», #1158).
 *
 * Архивный объект (#1342; правка решения владельца 13.10 — вместо
 * «дизейбл + пояснение»): строка действий не рендерится вовсе — ни кнопок,
 * ни подписи, для любого состояния правила; сервер и так отвечает 409 на
 * любую мутацию архивного объекта, а состояние паузы несут пассивные
 * признаки — бейдж «• На паузе» карточки и подзаголовок строки списка.
 *
 * Чистая функция над сущностью — витест
 * держит матрицу, живая приёмка — проводку.
 */
export type PaymentDetailAction =
  | 'pause'
  | 'resume'
  | 'edit'
  | 'editRental'
  | 'pay'
  | 'complete'
  | 'completeRental';

export function paymentDetailActions(
  payment: Pick<Payment, 'isRentalManaged' | 'isRentalCompleted'>,
  paused: boolean,
  endedRule: boolean,
  settled: boolean,
  propertyArchived: boolean,
): ReadonlyArray<PaymentDetailAction> {
  if (propertyArchived) {
    return [];
  }
  if (payment.isRentalManaged) {
    if (payment.isRentalCompleted) {
      return [];
    }
    return settled ? ['editRental', 'completeRental'] : ['editRental', 'pay'];
  }
  if (paused) {
    return endedRule ? ['edit', 'pay'] : ['resume', 'edit', 'pay'];
  }
  if (endedRule) {
    return settled ? ['edit', 'complete'] : ['edit', 'pay'];
  }
  return settled ? ['pause', 'edit', 'complete'] : ['pause', 'edit', 'pay'];
}
