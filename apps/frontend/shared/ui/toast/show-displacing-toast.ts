import { toast } from 'react-toastify/unstyled';

/**
 * Показ тоста с вытеснением — канон «максимум один тост на экране»
 * (решение владельца 13.10): активные тосты гасятся ДО показа нового,
 * старый играет exit-анимацию, новый въезжает одновременно. Карточки
 * ложатся на одно место (absolute-укладка в ToastProvider.module.css,
 * дополнение решения 13.10 «просто в бок уходило и все»): заменяющая
 * карточка появляется ровно на месте старой — въезд с края (десктоп —
 * справа, мобайл — сверху), улёт вбок, без вертикальных «поездов».
 * Все показы тостов платформы идут через эту обёртку. Очереди
 * «догоняющих» тостов нет по построению: проп `limit` с контейнера
 * снят — в react-toastify v11 тост остаётся в счётчике показанных до
 * конца exit+collapse, поэтому при limit={1} новый тост ждал бы в
 * нативной очереди ~600мс и замена шла бы «ступенькой».
 */
export function showDisplacingToast<T>(show: () => T): T {
    // dismiss() без аргументов гасит все активные тосты контейнера.
    toast.dismiss();
    return show();
}
