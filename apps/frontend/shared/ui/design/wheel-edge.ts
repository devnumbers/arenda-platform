/** Математика края линейной ленты колеса (#1427): триггер удлинения
 * срабатывает не у самой стены, а из глубокой зоны — так физический край
 * недостижим одним жестом и достройка всегда успевает раньше инерции.
 *
 * Физика флика (замер живой приёмки 2026-10-13): начальная скорость
 * жёсткого свайпа ~8000px/s, BrowserScroller гасит её за τ≈325ms —
 * один флик покрывает не больше v₀·τ ≈ 2600px ≈ 54 ряда. Прежний
 * триггер за 2 ряда (96px) инерция пролетала за ~12мс — React не успевал
 * достроить ленту, momentum упирался в настоящий край скролла и гас:
 * прокрутка «просто останавливалась».
 *
 * Зона 80 рядов (3840px) даёт полуторный запас против максимального
 * флика: из любой точки зоны стену не достать одним жестом, а достройка
 * получает на реакцию сотни миллисекунд. Достройка вперёд (onNearEnd —
 * приписка рядов в конец) не трогает позицию скролла — невидима для
 * инерции в любой момент; достройка назад (onNearStart — приписка в
 * начало со сдвигом scrollTop) пишется в паузе после остановки колеса
 * (settle): запись позиции посреди инерции её убивает. */

/** Рядов в зоне триггера у края: больше максимального пролёта флика. */
export const WHEEL_NEAR_EDGE_ROWS = 80;

/** Рядов покрывает самый жёсткий флик (v₀·τ / высота ряда). */
export const WHEEL_MAX_FLING_ROWS = 54;

/** Достигнут ли край ленты (удлинение вперёд). Короткая лента (меньше
 * зоны) целиком в зоне — первый же скролл её удлиняет. */
export function isNearEnd(row: number, length: number): boolean {
  return row >= length - WHEEL_NEAR_EDGE_ROWS;
}

/** Достигнут ли край ленты (удлинение назад). */
export function isNearStart(row: number): boolean {
  return row <= WHEEL_NEAR_EDGE_ROWS - 1;
}
