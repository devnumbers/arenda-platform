/** Якорь дорисовки ленты месяцев назад (пикер периода). Инварианта: кадр,
 * который видит человек в момент подстановки месяцев, не меняется —
 * позиция возвращается ОТ ФАКТИЧЕСКОГО места скролла плюс прирост высоты,
 * а не от снимка на триггере. Пока React рисует порцию месяцев,
 * инерция едет дальше (под нагрузкой — доезжает до стены), и возврат
 * к снимку прыгал бы назад на дрейф: живой замер #1428 поймал скачок
 * видимого месяца на 17.7px именно на таком кадре. Пиксель у верхней
 * кромки до дорисовки остаётся у верхней кромки после — смещается только
 * его координата в ленте. */

/** Позиция скролла после дорисовки: фактическое место плюс прирост
 * высоты ленты. */
export function compensatedScrollTop(
  now: { readonly scrollTop: number },
  scrollHeightBefore: number,
  scrollHeightAfter: number,
): number {
  return now.scrollTop + (scrollHeightAfter - scrollHeightBefore);
}
