/** Гейт приписки ленты бесконечного календаря (план 050): одна порция
 * «в полёте» — скролл-события одного кадра не суммируют порции в один
 * DOM-коммит.
 *
 * Фон: под моментумом телефона скролл-события приходят пачками в кадре,
 * и каждое запрашивало приписку 6–48 месяцев (flingChunks — кэп на
 * событие); React батчит запросы одного кадра в один рендер, и DOM-встав
 * разрастался кратно числу событий — на телефоне это паузы кадра
 * 150–600 мс прямо в инерции (замер 17.10: 20 всплесков — scrollHeight
 * 3.8k → 52.9k px, паузы коммитов до 112 мс при CPU ×6). Гейт держит не
 * более одной незавершённой приписки: запросы, пришедшие до того, как
 * предыдущая доехала до DOM, склеиваются в неё; settled() вызывает
 * эффект рендера приписки — следующий кадр снова может просить порцию.
 *
 * Душащий-CPU сценарий 042 не страдает: scroll-события там редки
 * (7 на 90 000px флика), к моменту каждого предыдущая порция уже
 * уехала в DOM — гейт пропускает каждую. */

export interface CalendarPrependGate {
  /** Запрос приписки: порция к применению или null — предыдущая ещё в
   * полёте, запрос склеился с ней. */
  request(chunks: number): number | null;
  /** Приписка доехала до DOM (эффект рендера приписки). */
  settled(): void;
  /** Есть ли незавершённая приписка (для тестов и отладки). */
  readonly pending: boolean;
}

export function createPrependGate(): CalendarPrependGate {
  let pending = false;
  return {
    request(chunks: number) {
      if (pending || chunks <= 0) {
        return null;
      }
      pending = true;
      return chunks;
    },
    settled() {
      pending = false;
    },
    get pending() {
      return pending;
    },
  };
}
