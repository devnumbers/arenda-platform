/** Константы удлинения ленты годов шита «Месяц и год» (решение владельца
 * 2026-10-13: «годы от текущего и к будущему без конца» и уточнение
 * 2026-10-13 о бесконечном прошлом истории операций).
 *
 * Вперёд (YEARS_EXTENSION) лента достраивается мгновенно у края — приписка
 * рядов в конец не трогает позицию скролла и невидима; размер шага на
 * ощущение не влияет, стену убирает зона триггера колеса (wheel-edge.ts).
 *
 * Назад шаг доращивания (YEARS_BACKWARD_EXTENSION) приписывает ряды со
 * сдвигом scrollTop, который нельзя делать посреди инерции, — колесо
 * вызывает onNearStart в паузе. Шаг зеркалит стартовый посев (план 049,
 * решение владельца 17.10 — «поддёргивания при прокрутке в прошлое»,
 * покадровое репро WebKit): он обязан выносить позицию из зоны триггера
 * с запасом под самый жёсткий флик — зона (80) + флик (54) = 134, как и
 * сид. Прежние 400 были круглым запасом: каждая доращивка монтировала
 * 400 анимированных рядов, инвариант физики держится и на 134.
 *
 * Стартовый посев назад (YEARS_INITIAL_BACKWARD_SEED) — та же формула с
 * отдельным требованием (план 048, решение владельца
 * 17.10: «пикер так долго открывается» — посев 400 монтировал 401
 * анимированный ряд, замер открытия 858–1147мс против ~200мс у лёгких
 * модалок): гарантировать «первый жёсткий флик назад без стены» и
 * провести колесо через зону триггера, чтобы доращивание стартовало. */
import { WHEEL_MAX_FLING_ROWS, WHEEL_NEAR_EDGE_ROWS } from './wheel-edge';

/** Шаг удлинения ленты годов вперёд у нижнего края без границы. */
export const YEARS_EXTENSION = 25;

/** Шаг удлинения ленты годов назад у верхнего края без границы: зеркало
 * сида — зона триггера + максимальный флик (план 049). */
export const YEARS_BACKWARD_EXTENSION = 134;

/** Глубина стартового посева в прошлое: зона триггера + максимальный
 * флик (wheel-edge.ts) — стена недостижима первым фликом, доращивание
 * стартует на его пути. */
export const YEARS_INITIAL_BACKWARD_SEED =
  WHEEL_NEAR_EDGE_ROWS + WHEEL_MAX_FLING_ROWS;

/** Стартовое окно ленты годов шита без границ: от текущего
 * года вперёд без конца (решение владельца 2026-10-13 — «годы от текущего
 * и к будущему»). Выбранный год всегда внутри ленты: старт не позже
 * выбранного (чужое value из прошлого не выкидывается — колесо обязано
 * найти своё значение), конец — на 25 лет дальше большего из выбранного
 * и текущего: запас под жёсткий флик (~50 рядов инерции — два окна),
 * чтобы прокрутка вперёд не упиралась в край ленты. У нижнего края
 * onNearEnd колеса удлиняет ленту ещё на 25 (YEARS_EXTENSION), рост
 * невидим — синхронизация колеса не считает приписку рядов сменой
 * значения. */
export function initialYearsWindow(
  selectedYear: number,
  currentYear: number,
): { readonly start: number; readonly end: number } {
  return {
    start: Math.min(currentYear, selectedYear),
    end: Math.max(currentYear, selectedYear) + 25,
  };
}
