/** Решение синка колеса (план 049): каким действием синк-эффект
 * восстанавливает позицию ленты при очередном рендере.
 *
 * Фон: после приписки рядов СВЕРХУ (перекройка месяцев года при смене
 * года, доращивка ленты годов назад) ряд выбранного значения сдвигается,
 * и позицию надо вернуть самому. Прежняя ставка на «реснап до пейнта»
 * (комментарий синк-эффекта, фикс #1429) работает на Chromium, но на
 * WebKit реснап промахивается на соседние ряды (репро 17.10: ноябрь
 * вместо октября при разблокировке месяцев) или не происходит вовсе
 * (~13 кадров год на 400 раньше — репро доращивки). Коррекция после
 * пейнта закрашивает чужой кадр; коррекция роллом при доращивке,
 * совпавшей со сменой значения, катит ~19 000px через века. Отсюда
 * правила:
 *
 * - «skip» — индекс значения не сдвинулся и доращивки не было: позиция
 *   уже правильная (после собственного скролла человека ничего не
 *   дёргается);
 * - «direct» — мгновенная установка ряда значения до пейнта: первое
 *   монтирование; перекройка ленты без смены значения; доращивка назад
 *   (с ней или без — колесо уже стоит на своём году, сдвигается только
 *   смещение, ролл не имеет смысла никогда);
 * - «roll» — плавная докрутка при обычной смене значения (клавиатура,
 *   внешний выбор): колесо действительно едет к ряду. */

export type WheelSyncPlan = 'skip' | 'direct' | 'roll';

export type WheelSyncState = {
  /** Первый рендер колеса: выбранный ряд садится в центр мгновенно. */
  readonly instant: boolean;
  /** Индекс значения на прошлом синке (null — синка ещё не было). */
  readonly syncFrom: number | null;
  /** Индекс значения в текущей ленте. */
  readonly valueIndex: number;
  /** Значение изменилось с прошлого рендера (не перекройка ленты). */
  readonly valueChanged: boolean;
  /** С прошлого синка была доращивка ленты назад (onNearStart). */
  readonly grewAtStart: boolean;
};

export function planWheelSync(state: WheelSyncState): WheelSyncPlan {
  if (state.instant) return 'direct';
  if (!state.valueChanged && !state.grewAtStart && state.syncFrom === state.valueIndex) {
    return 'skip';
  }
  if (state.grewAtStart) return 'direct';
  if (state.valueChanged) return 'roll';
  return 'direct';
}
