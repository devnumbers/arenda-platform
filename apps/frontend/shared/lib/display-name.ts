/**
 * ФИО-канон отображаемых имён (карта #1324, протокол D4): живые части
 * профиля собираются в «Имя Фамилия»; недостающая часть просто не пишется;
 * имени нет — «Пользователь» (голая фамилия не показывается). Суффикс
 * «(Вы)» для себя — забота вида (серый суффикс поверх канонного имени,
 * канон шита фильтров #710), хелпер возвращает только базу. Бекенд-канон —
 * access.DisplayNameOf; фронтовая точка одна — здесь.
 */

/** Обезличенная подпись пользователя без имени (канон #1105, аменд #1123). */
export const ANONYMOUS_USER_NAME = 'Пользователь';

/** Базовое отображаемое имя по живым частям профиля: «Имя» / «Имя Фамилия»,
 * без имени — «Пользователь» независимо от фамилии (D4). */
export function displayUserName(firstName: string, lastName: string): string {
  const name = firstName.trim();
  if (name === '') {
    return ANONYMOUS_USER_NAME;
  }
  const surname = lastName.trim();
  return surname === '' ? name : `${name} ${surname}`;
}
