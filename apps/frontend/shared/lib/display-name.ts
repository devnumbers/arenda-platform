/**
 * ФИО-канон отображаемых имён (карта #1324, протокол D4): живые части
 * профиля собираются в «Имя Фамилия»; недостающая часть просто не пишется;
 * имени нет — «Пользователь» (голая фамилия не показывается). База титула
 * своей строки — displayOwnUserName (фамилия своей строки не пишется,
 * D4); серый суффикс «(Вы)» поверх базы — забота вида: рисует его
 * MeSuffix (shared/ui/design), текст — OWN_USER_NAME_SUFFIX отсюда
 * (канон шита фильтров #710, извлечено #1356). Бекенд-канон —
 * access.DisplayNameOf; фронтовая точка одна — здесь.
 */

/** Обезличенная подпись пользователя без имени (канон #1105, аменд #1123). */
export const ANONYMOUS_USER_NAME = 'Пользователь';

/** Текст серого суффикса своей строки — с ведущим пробелом: рисуется
 * вплотную к имени (MeSuffix), строкой берёт aria-label своей строки
 * (шит фильтров). Единственная точка текста «(Вы)». */
export const OWN_USER_NAME_SUFFIX = ' (Вы)';

/** Базовое отображаемое имя по живым частям профиля: «Имя» / «Имя Фамилия»,
 * без имени — «Пользователь» независимо от фамилии (D4). */
export function displayUserName(firstName: string, lastName: string): string {
  const name = firstName.trim();
  if (name === '') {
    return ANONYMOUS_USER_NAME;
  }
  const surname = lastName.trim();
  return surname === '' ? name : `${name} ${surname}`;
}

/** База титула своей строки: ФИО-канон D4 без фамилии — фамилия своей
 * строки не пишется (макет «Даниил (Вы)»); имени нет — «Пользователь».
 * Серый суффикс «(Вы)» поверх базы рисует вид (MeSuffix). */
export function displayOwnUserName(firstName: string): string {
  return displayUserName(firstName, '');
}
