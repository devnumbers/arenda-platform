import { ROUTES } from '@/shared/config/routes';
import type { TariffName } from '@/shared/model/tariff';

/** Платные разделы кабинета (карта #997, ADR 0064): маршруты, доступные
 * только платным тарифам. proxy.ts вызывает гейт на каждом /me-гейтованном
 * маршруте: null-подписка считается базовым тарифом, grace/cancelled на
 * платном тарифе имя сохраняют — статус не проверяется. Обход мимо UI ловит
 * бекенд-гейт (402 tariff_required); реестры фронта и бека расходятся
 * осознанно (ревизия ADR 0064 #1462): новый платный экран добавляет паттерн
 * здесь и бекенд-гейт — оверрайд роутов в httpserver/server.go для платных
 * групп целиком либо use-case-шов для роль-осведомлённых групп (сейчас одна —
 * access-роуты объекта: участник объекта на basic читает список, гейт бьёт
 * только владельца). Карта «Совместный доступ и История на basic» #1459
 * пересобирает экраны 1–3 — паттерны снимаются тикетами экранов. Цель
 * редиректа — страница выбора тарифа без контекста (решение владельца 30.09:
 * плашка-контекст в дизайне не нужна, снесена вместе с query gate). */
const PAID_SECTION_ROUTES: ReadonlyArray<{ readonly pattern: RegExp }> = [
    {
        // Экран 1 карты #997: «Совместный доступ объекта» — список участников
        // и приглашение. Владельцу бекенд отвечает 402 (гейт в use-case'ах
        // access, #1462); участнику объекта чтения на basic разрешены —
        // паттерн держится до пересборки экрана тикетом карты #1459.
        pattern: /^\/properties\/[^/]+\/participants(?:\/|$)/,
    },
    {
        // Экран 2 карты #997: «Участники» — вложенные маршруты раздела
        // (поиск, приглашение, страница участника, права). Сама страница
        // /participants открыта на basic как пустое состояние-апселл (D2
        // #1313, ревизия ADR 0064): список скрыт до оплаты, чтение API на
        // basic не вызывается — эндпоинты остаются за бекенд-гейтом.
        pattern: /^\/participants\/.+/,
    },
    {
        // Экран 3 карты #997: «История действий» — лента и вложенные страницы
        // участника и объекта; фильтры — шит на хабе, их опции обслуживает
        // гейтуемый бекенд-эндпойнт GET /history/filters.
        pattern: /^\/history(?:\/|$)/,
    },
];

/** Путь редиректа на выбор тарифа или null, когда маршрут не платный либо
 * тариф платный. */
export function paidSectionGateRedirect(
    pathname: string,
    tariffName: TariffName | null,
): string | null {
    const gated = PAID_SECTION_ROUTES.some(({ pattern }) =>
        pattern.test(pathname),
    );
    if (!gated) {
        return null;
    }
    if (tariffName !== null && tariffName !== 'basic') {
        return null;
    }
    return ROUTES.profileTariffChange;
}
