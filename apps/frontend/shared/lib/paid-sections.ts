import { ROUTES } from '@/shared/config/routes';
import type { TariffName } from '@/shared/model/tariff';

/** Платные разделы кабинета (карта #997, ADR 0064): маршруты, доступные
 * только платным тарифам. proxy.ts вызывает гейт на каждом /me-гейтованном
 * маршруте: null-подписка считается базовым тарифом, grace/cancelled на
 * платном тарифе имя сохраняют — статус не проверяется. Обход мимо UI ловит
 * бекенд-гейт (402 tariff_required); реестры фронта и бека расходятся
 * осознанно (ревизия ADR 0064 #1462): новый платный экран добавляет паттерн
 * здесь и бекенд-гейт — оверрайд роутов в httpserver/server.go для платных
 * групп целиком либо use-case-шов для роль-осведомлённых групп (сейчас две —
 * access-роуты объекта #1462: участник объекта на basic читает список, гейт
 * бьёт только владельца; история #1465: лента без сужения 402, сужение —
 * только по объектам активного участия). Цель редиректа обоих паттернов —
 * интерстишал «Совместный доступ недоступен» #1470 (решение владельца
 * 15.10.2026, ревизия D3 карты #1459: deep-маршруты участников и лента
 * истории — поверхности совместного доступа; выбор тарифа — следующей
 * кнопкой с интерстишала, прежняя безконтекстная цель «выбор тарифа»
 * 30.09 заменена им для этих поверхностей). Экранная разводка клика
 * «Совместного доступа» — sharingGateRedirect ниже; пер-объектные
 * маршруты шаринга и объектные поверхности истории сняты с proxy-гейта
 * (#1463, #1466). */
const PAID_SECTION_ROUTES: ReadonlyArray<{ readonly pattern: RegExp }> = [
    {
        // Экран 2 карты #997: «Участники» — вложенные маршруты раздела
        // (поиск, приглашение, страница участника, права). Сама страница
        // /participants открыта на basic как пустое состояние-апселл (D2
        // #1313, ревизия ADR 0064): список скрыт до оплаты, чтение API на
        // basic не вызывается — эндпоинты остаются за бекенд-гейтом.
        // Пер-объектные маршруты /properties/{id}/participants… сняты с
        // proxy-гейта картой #1459 (#1463): proxy роль читателя не знает —
        // участник объекта читает их на любом тарифе (бекенд-гейт
        // роль-осведомлённый, #1462), владельца на basic разводит экранная
        // разводка (sharingGateRedirect ниже).
        pattern: /^\/participants\/.+/,
    },
    {
        // Экран 3 карты #997: «История действий» — с разводки карты #1459
        // (#1466) proxy держит только ленту: вход в ленту basic не нужен
        // (глобальная область бекенд-гейта owner-scope, #1465 — платная
        // для всех, включая участников). Объектные поверхности
        // /history/properties/{id} и /history/participants/{p}/properties/{id}
        // выпущены из proxy-гейта: участник объекта читает их на любом
        // тарифе (бекенд-гейт роль-осведомлённый, #1465), владельца на
        // basic разводит экранная разводка (sharingGateRedirect ниже).
        pattern: /^\/history\/?$/,
    },
];

/** Путь редиректа на интерстишал «Совместный доступ недоступен» (#1470)
 * или null, когда маршрут не платный либо тариф платный. */
export function paidSectionGateRedirect(
    pathname: string,
    tariffName: TariffName | null,
): string | null {
    const gated = PAID_SECTION_ROUTES.some(({ pattern }) =>
        pattern.test(pathname),
    );
    if (!gated) {
        return null;
    }
    if (tariffName !== null && tariffName !== 'basic') {
        return null;
    }
    return ROUTES.profileTariffSharing;
}

/** Разводка «Совместного доступа» для владельца (карта #1459, решение
 * владельца 15.10.2026, #1463; регистр screen-разводки ADR 0064): владелец
 * на basic идёт на интерстишал «Совместный доступ недоступен» #1470 —
 * и из клика на экране объекта (кебаб и секция «Управление»), и как
 * страховка на гейтованных экранах после снятия их паттернов с
 * proxy-гейта: страница участников (#1463) и объектные поверхности
 * истории (#1466) — глубокие ссылки, уведомления, закладки. Участник
 * объекта пользуется страницей на любом тарифе — «пригласили, значит
 * пользуется», бекенд-гейт роль-осведомлённый (#1462, #1465). isPaid —
 * optimistic-умолчание канона экранов: подписка ещё не загрузилась
 * (или её нет) — считается платным, бекенд-гейт остаётся истиной. */
export function sharingGateRedirect(
    canManageMembers: boolean,
    isPaid: boolean,
): string | null {
    if (!canManageMembers || isPaid) {
        return null;
    }
    return ROUTES.profileTariffSharing;
}
