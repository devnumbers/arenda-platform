/**
 * Реестр якорёных роутов (карта #1324, D8.1): страницы истории
 * позиционирует сама лента — якорь «с конца» лейаут-эффектом до пэйнта
 * (widgets/history/lib/feed-scroll.ts), поэтому глобальный «всегда верх»
 * (ScrollToTop) их не скроллит: в том же коммите он выполняется после
 * якоря и затирал бы его (корень «открытия с верха», #1281-семейство).
 *
 * Позиция чтения при возврате «Назад» снята решением владельца 10.10.2026
 * (#1319): лента всегда открывается на последних действиях.
 */

/** Роуты, чьё позиционирование ведёт сама лента (якорь «с конца»). */
export function isAnchoredRoute(pathname: string): boolean {
  return pathname === '/history' || pathname.startsWith('/history/');
}
