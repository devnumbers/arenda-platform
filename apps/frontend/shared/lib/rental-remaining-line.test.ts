import { describe, expect, it } from 'vitest';
import { rentalRemainingLine } from './rental-remaining-line';

/** Общая метка остатка аренды для трёх поверхностей (решение #1387):
 * детализация, блок «Аренда» на объекте, бейдж списка (бейдж #584 теряет
 * своё правило «Осталось меньше месяца»). */

describe('rentalRemainingLine', () => {
  it('остаток месяцами и больше — как сегодня: полные месяцы, склонение', () => {
    expect(rentalRemainingLine('2026-09-05', '2028-08-05')).toBe('Осталось 23 месяца аренды');
    expect(rentalRemainingLine('2026-09-05', '2026-10-05')).toBe('Остался 1 месяц аренды');
    expect(rentalRemainingLine('2026-09-05', '2026-11-05')).toBe('Осталось 2 месяца аренды');
    expect(rentalRemainingLine('2026-09-05', '2027-02-05')).toBe('Осталось 5 месяцев аренды');
    expect(rentalRemainingLine('2026-09-05', '2027-08-05')).toBe('Осталось 11 месяцев аренды');
    expect(rentalRemainingLine('2026-09-05', '2028-06-05')).toBe('Остался 21 месяц аренды');
    expect(rentalRemainingLine('2026-09-05', '2035-02-05')).toBe('Остался 101 месяц аренды');
    expect(rentalRemainingLine('2026-09-05', '2035-12-05')).toBe('Осталось 111 месяцев аренды');
  });

  it('остаток меньше месяца — календарные дни (слово владельца 13.10, #1387)', () => {
    expect(rentalRemainingLine('2026-09-10', '2026-09-25')).toBe('Осталось 15 дней аренды');
    expect(rentalRemainingLine('2026-09-10', '2026-09-11')).toBe('Остался 1 день аренды');
    expect(rentalRemainingLine('2026-09-10', '2026-09-12')).toBe('Осталось 2 дня аренды');
    // 21 день — граница месяца не дотягивается (полных месяцев 0), склонение дневное.
    expect(rentalRemainingLine('2026-09-10', '2026-10-01')).toBe('Остался 21 день аренды');
  });

  it('плановое окончание сегодня — «Заканчивается сегодня» (прецедент «Платёж сегодня»)', () => {
    expect(rentalRemainingLine('2026-09-10', '2026-09-10')).toBe('Заканчивается сегодня');
  });

  it('план прошёл — строки нет: сцену держат статусные тексты', () => {
    expect(rentalRemainingLine('2026-09-10', '2026-09-08')).toBeUndefined();
  });

  it('бессрочная аренда (планового окончания нет) — строки нет', () => {
    expect(rentalRemainingLine('2026-09-10', null)).toBeUndefined();
  });
});
