/**
 * Подпись почтового тумблера шага 4 — одна формула для обеих вилок
 * (шаг настроек аренды #826 и шаг 4 платежей #825): «Будем напоминать
 * {предмет} на вашу почту {email}», без email — хвост обрывается после
 * «почту». Строки обеих вилок закреплены дословно — править формулу
 * нельзя без синхронного прогона e2e-хвостов напоминаний.
 */
export function emailReminderCaption(subject: string, email: string | null): string {
  return `Будем напоминать ${subject} на вашу почту${email !== null ? ` ${email}` : ''}`;
}
