import { describe, expect, it } from 'vitest';
import { rentalExtendMinDate } from './extend-model';

describe('rentalExtendMinDate', () => {
  it('срочная с будущим окончанием — строго позже текущего', () => {
    expect(rentalExtendMinDate('2027-03-23', '2026-09-23', '2026-09-23', 1)).toBe('2027-03-24');
  });

  it('окончание сегодня — первый доступный день завтра', () => {
    expect(rentalExtendMinDate('2026-09-23', '2026-03-10', '2026-09-23', 1)).toBe('2026-09-24');
  });

  it('needs_attention (окончание в прошлом) — от сегодня', () => {
    expect(rentalExtendMinDate('2026-09-01', '2026-03-10', '2026-09-23', 1)).toBe('2026-09-23');
  });

  it('бессрочная начавшаяся — от сегодня', () => {
    expect(rentalExtendMinDate(null, '2026-03-10', '2026-09-23', 1)).toBe('2026-09-23');
  });

  it('upcoming бессрочная (начало в будущем) — от дня после начала, не от сегодня', () => {
    expect(rentalExtendMinDate(null, '2026-10-01', '2026-09-23', 1)).toBe('2026-10-02');
  });

  it('upcoming срочная — граница продления строже дня после начала', () => {
    expect(rentalExtendMinDate('2026-10-05', '2026-10-01', '2026-09-23', 1)).toBe('2026-10-06');
  });

  it('открытая незапущенная: первое вхождение дня оплаты позже «сегодня» — ведёт оно (кейс 32 research #1150)', () => {
    // Старт 10-го, день оплаты 25-е, сегодня 12-е: продление до 20-го
    // оставило бы аренду без платежей — минимум 25-е.
    expect(rentalExtendMinDate(null, '2026-10-10', '2026-10-12', 25)).toBe('2026-10-25');
  });

  it('первое вхождение строже текущего окончания +1 (легаси-пара с дырой)', () => {
    // Срочная с окончанием 20-го при дне оплаты 25-е — дыра «0 платежей»
    // из прежней версии; продление её не удерживает.
    expect(rentalExtendMinDate('2026-10-20', '2026-10-10', '2026-10-12', 25)).toBe('2026-10-25');
  });

  it('«последний день месяца» — граница в конце месяца', () => {
    expect(rentalExtendMinDate(null, '2026-10-10', '2026-10-12', 'last')).toBe('2026-10-31');
  });

  it('день оплаты в день старта не поднимает прежних границ', () => {
    expect(rentalExtendMinDate(null, '2026-10-10', '2026-10-06', 10)).toBe('2026-10-11');
  });
});
