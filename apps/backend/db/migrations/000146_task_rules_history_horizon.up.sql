-- Горизонт истории правила (ADR 0051 в правке 2026-10-01): «Удалить все
-- выполненные» начинает сносить выполненные задачи и живых правил, и каждая
-- затронутая строка больше не держит дедуп-ключ тика. Вместо надгробий
-- (решение #496 «статус-надгробий нет») правило получает пер-правильную
-- границу: вхождения раньше history_before удалены навсегда и тиком не
-- материализуются; горизонт подавляет только создание — стоящие строки не
-- трогает. Недатированному правилу дата не имеет смысла: любое NOT NULL
-- значение — маркер спячки «задача снесена, не воссоздавать», правка
-- правила маркер сбрасывает. NULL = горизонт не поднимался.
ALTER TABLE task_rules
    ADD COLUMN history_before DATE;
