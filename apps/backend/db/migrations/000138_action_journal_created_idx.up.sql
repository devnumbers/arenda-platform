-- Ведущий ключ-индекс общей ленты (карта #704, тикет #708, ADR 0061 §7).
-- Три курсорных индекса 000136 ведут развёртки от скоупа (объект/актёр/вид),
-- но у общей ленты «История действий» (и у поиска с keyset-пагинацией)
-- скоупа нет: без индекса по (created_at DESC, id DESC) планировщик на
-- каждую страницу сортирует весь журнал. Перф-проба на сиде 120k строк
-- (HISTORY_PERF_PROBE=1): ~350 мс на страницу ленты до индекса, единицы
-- миллисекунд после — сканирование останавливается на LIMIT.
CREATE INDEX idx_action_journal_created
    ON action_journal (created_at DESC, id DESC);
