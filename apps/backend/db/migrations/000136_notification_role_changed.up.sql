-- Порядок каталога: в группе Совместный доступ, после member_left, перед
-- тарифной группой (AFTER по уже существующему значению — требование
-- require-enum-value-ordering).
ALTER TYPE notification_event_type ADD VALUE 'access_role_changed' AFTER 'member_left';
