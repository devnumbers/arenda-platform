-- Пояснения строки журнала (протокол D1, тикет #1317, карта #1324): серые
-- строки-пояснения нового шаблона («Название: «Моя квартира» → «Квартира
-- №124»»), собираются билдерами rows.go ПРИ ЗАПИСИ и рендерятся фронтом
-- дословно — читающий путь без каталога форматирования (канон ADR 0061 §6).
-- NULL у строк, записанных до D1: они рендерятся одним заголовком —
-- осознанное решение владельца.
-- Отдельного индекса нет: details ничем не фильтруется и отдельно не ищется —
-- поиск материализуется колонкой searchable (две GIN-ноги 000140), отдельный
-- индекс по jsonb удвоил бы write-overhead при нуле читателей.
SET lock_timeout = '1s';
SET statement_timeout = '5s';

ALTER TABLE action_journal
    ADD COLUMN details JSONB;
