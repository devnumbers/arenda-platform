-- Пер-платёжный флаг «уведомлять об автоплатеже» (#1189): получать ли событие
-- «Автоплатёж исполнен» (payment_auto_paid) по правилу — гейт читают три
-- auto-paid ноги издателя уведомлений (скан, букинг, разрешение в момент
-- доставки). Дефолт false — новые правила создаются молчащими (макет
-- 3214-72739, решение владельца по гриллингу #1186); существующим
-- автоплатежам ставим true — без поведенческого регресса (то же решение).
-- Флаг живёт независимо от auto_pay после создания: переключение режима
-- правило не переписывает.
ALTER TABLE payments ADD COLUMN notify_auto_paid BOOLEAN NOT NULL DEFAULT false;
UPDATE payments SET notify_auto_paid = true WHERE auto_pay = true;
