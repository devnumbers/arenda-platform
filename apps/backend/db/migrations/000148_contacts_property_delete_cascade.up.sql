-- Удаление объекта уносит его контакты (карта #1047, тикет #1049): осознанный
-- разворот решения ADR 0054 §2 (решение владельца 02.10.2026) — контакт снова
-- ребёнок объекта, а не самостоятельная запись владельца. UI-диалог удаления
-- объекта уже обещает «контакты будут удалены» — рассинхрон UI и бека
-- закрывается в пользу удаления. Контакт без объекта остаётся в книге
-- владельца; ссылка аренды на контакт-тенанта (000120 ON DELETE SET NULL)
-- не меняется: снос контакта-тенанта обнуляет rental.contact_id, аренда
-- выживает. Смена referential action — DROP CONSTRAINT + ADD CONSTRAINT
-- одним стейтментом (канонический рецепт; констрейнт — автоимя 000119).
-- Номер 000147 занят параллельной веткой push-contract-1037 (#1029, пуши):
-- дубли версий миграционный линт не ловит, разрыв в последовательности —
-- артефакт parallel-dev, не пропавшая миграция.
ALTER TABLE contacts
    DROP CONSTRAINT contacts_property_id_fkey,
    ADD CONSTRAINT contacts_property_id_fkey
        FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE CASCADE;
