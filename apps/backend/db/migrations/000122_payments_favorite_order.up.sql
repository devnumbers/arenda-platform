-- Ручной порядок избранных платежей (карта #573, тикет #576; поправка ADR
-- 0049). Позиция живёт на правиле рядом с флагом, который она упорядочивает
-- (канон #461: избранный — правило целиком); отдельная таблица дублировала
-- бы связь, не имея дюрального инварианта пауз. NULL = правило никогда не
-- было в сохранённом порядке: новое и старое избранное сортируется в конец
-- (правило чтения «новое избранное — в конец»), PUT favorite держит
-- инвариант атомарно — снятие звезды очищает позицию, повторное — снова
-- NULL, то есть конец списка.
ALTER TABLE payments ADD COLUMN favorite_order BIGINT;
ALTER TABLE payments ADD CONSTRAINT payments_favorite_order_check
    CHECK (favorite_order IS NULL OR is_favorite);
