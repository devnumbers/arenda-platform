// Emits the frontend TypeScript artifacts under
//   apps/frontend/features/property-attributes/lib/generated/
//
// Files: attr-keys.ts, catalog.ts, labels.ts, validate.ts
//
// These mirror the hand-written lib/{catalog,labels,validate}.ts and
// model/attr-keys.ts semantically. Integration (rewiring app imports to
// generated/) is a separate step (1.4b). Here we only produce the code.

import {
  TYPE_ORDER,
  TYPE_ALIASES,
  fieldsFor,
  enumOptionKeys,
  allFieldKeys,
  mergedEnumOptions,
} from './model.mjs';

const HEADER = `// Code generated by tools/property-attributes/generate.mjs from catalog.json. DO NOT EDIT.`;

// ----- attr-keys.ts -----
export function emitAttrKeys(catalog) {
  const keys = allFieldKeys(catalog);
  const union = keys.map((k) => `  | ${JSON.stringify(k)}`).join('\n');
  const arr = keys.map((k) => `  ${JSON.stringify(k)},`).join('\n');
  return `${HEADER}

export type AttrKey =
${union};

export const attrKeys: readonly AttrKey[] = [
${arr}
] as const;
`;
}

// ----- catalog.ts -----
function emitFieldList(typeKey, catalog) {
  const entries = fieldsFor(catalog, typeKey);
  const lines = entries.map(({ key, def }) => {
    switch (def.kind) {
      case 'enum': {
        const opts = enumOptionKeys(def).map((o) => JSON.stringify(o)).join(', ');
        return `  { key: ${JSON.stringify(key)}, kind: 'enum', options: [${opts}], group: ${groupLit(def.group)} },`;
      }
      case 'number':
        return `  { key: ${JSON.stringify(key)}, kind: 'number', unit: ${JSON.stringify(def.unit)}, decimals: ${def.decimals}, group: ${groupLit(def.group)} },`;
      case 'integer':
        return `  { key: ${JSON.stringify(key)}, kind: 'integer', group: ${groupLit(def.group)} },`;
      case 'string':
        return `  { key: ${JSON.stringify(key)}, kind: 'string', maxLen: ${def.maxLen}, group: ${groupLit(def.group)} },`;
      default:
        throw new Error(`unknown kind for field ${key}: ${def.kind}`);
    }
  });
  return lines.join('\n');
}

function groupLit(group) {
  return group === null ? 'null' : JSON.stringify(group);
}

export function emitCatalog(catalog) {
  const primaries = TYPE_ORDER.filter((t) => !TYPE_ALIASES[t]);
  // Declare primary field lists, then alias exports (apartments = apartmentFields,
  // commercial = officeFields) inside the catalog object literal.
  const listBlocks = primaries.map((t) => {
    return `const ${t}Fields: AttrFieldList = [
${emitFieldList(t, catalog)}
];`;
  });

  const catalogEntries = TYPE_ORDER.map((t) => {
    if (TYPE_ALIASES[t]) {
      const primary = TYPE_ALIASES[t];
      return `  ${JSON.stringify(t)}: ${primary}Fields,`;
    }
    return `  ${JSON.stringify(t)}: ${t}Fields,`;
  }).join('\n');

  return `${HEADER}

import type { PropertyType } from '@/entities/property';
import type { AttrKey } from './attr-keys';

export type AttrGroup = 'about_object' | 'about_building' | 'about_house' | 'about_land';

export type AttrField =
  | {
      readonly key: AttrKey;
      readonly kind: 'enum';
      readonly options: readonly string[];
      readonly group: AttrGroup | null;
    }
  | {
      readonly key: AttrKey;
      readonly kind: 'number';
      readonly unit: 'м²' | 'сотки' | 'м';
      readonly decimals: number;
      readonly group: AttrGroup | null;
    }
  | {
      readonly key: AttrKey;
      readonly kind: 'integer';
      readonly group: AttrGroup | null;
    }
  | {
      readonly key: AttrKey;
      readonly kind: 'string';
      readonly maxLen: number;
      readonly group: AttrGroup | null;
    };

export type AttrFieldList = readonly AttrField[];

${listBlocks.join('\n\n')}

export const catalog: Readonly<Record<PropertyType, AttrFieldList>> = {
${catalogEntries}
};

export const groupLabels: Readonly<Record<AttrGroup, string>> = {
  about_object: 'О квартире',
  about_building: 'О доме',
  about_house: 'О доме',
  about_land: 'Об участке',
};

export function fieldsForType(type: PropertyType): AttrFieldList {
  return catalog[type];
}

export function findField(type: PropertyType, key: AttrKey): AttrField | undefined {
  return fieldsForType(type).find((field) => field.key === key);
}
`;
}

// ----- labels.ts -----
export function emitLabels(catalog) {
  const keys = allFieldKeys(catalog);
  const fieldLabelsMap = keys
    .map((k) => {
      // Find the label: the first non-alias type that has this field.
      const label = findFieldLabel(catalog, k);
      return `  ${JSON.stringify(k)}: ${JSON.stringify(label)},`;
    })
    .join('\n');

  const enumMap = mergedEnumOptions(catalog);
  const enumBlocks = [];
  for (const fkey of keys) {
    const opts = enumMap.get(fkey);
    if (!opts || opts.size === 0) continue;
    const optLines = [...opts.entries()]
      .map(([oKey, oLabel]) => `    ${JSON.stringify(oKey)}: ${JSON.stringify(oLabel)},`)
      .join('\n');
    enumBlocks.push(`  ${JSON.stringify(fkey)}: {
${optLines}
  },`);
  }

  return `${HEADER}

import type { AttrKey } from './attr-keys';

export const fieldLabels: Readonly<Record<AttrKey, string>> = {
${fieldLabelsMap}
};

export const enumLabels: Readonly<
  Partial<Record<AttrKey, Readonly<Record<string, string>>>>
> = {
${enumBlocks.join('\n')}
};
`;
}

function findFieldLabel(catalog, fieldKey) {
  for (const t of TYPE_ORDER) {
    const real = TYPE_ALIASES[t] ?? t;
    const f = catalog.types[real].fields[fieldKey];
    if (f) return f.label;
  }
  throw new Error(`field ${fieldKey} not found in any type`);
}

// ----- validate.ts -----
// Кросс-правила согласованности полей сняты (решение владельца 23.10.2026):
// валидируются только минимумы, точность и принадлежность enum.
export function emitValidate(catalog) {
  return `${HEADER}

import type { PropertyType, PropertyAttributes } from '@/entities/property';
import { fieldsForType, findField } from './catalog';
import type { AttrKey } from './attr-keys';

export type AttrErrors = Partial<Record<AttrKey, string>>;

export function filterByType(
  type: PropertyType,
  attrs: PropertyAttributes,
): PropertyAttributes {
  const fields = fieldsForType(type);
  const allowed = new Set<string>(fields.map((field) => field.key));
  const result: Record<string, string | number> = {};
  for (const [key, value] of Object.entries(attrs)) {
    if (allowed.has(key) && (typeof value === 'string' || typeof value === 'number')) {
      result[key] = value;
    }
  }
  return result;
}

function fractionDigits(value: string | number): number {
  const str = typeof value === 'number' ? String(value) : value;
  const dot = str.indexOf('.');
  if (dot === -1) return 0;
  return str.length - dot - 1;
}

export function validateField(
  type: PropertyType,
  key: AttrKey,
  value: string | number | undefined,
): string | undefined {
  const def = findField(type, key);
  if (!def) {
    return undefined;
  }
  if (value === undefined) {
    return undefined;
  }
  if (typeof value === 'string' && value === '') {
    return undefined;
  }

  if (def.kind === 'enum') {
    if (typeof value === 'string' && def.options.includes(value)) {
      return undefined;
    }
    return 'значение некорректно';
  }

  if (def.kind === 'number') {
    const parsed = typeof value === 'number' ? value : Number(value);
    if (Number.isNaN(parsed)) {
      return 'значение некорректно';
    }
    if (fractionDigits(value) > def.decimals) {
      return \`не более \${def.decimals} знаков после запятой\`;
    }
    return undefined;
  }

  if (def.kind === 'integer') {
    const parsed = typeof value === 'number' ? value : Number(value);
    if (!Number.isInteger(parsed)) {
      return 'значение некорректно';
    }
    return undefined;
  }

  // def.kind === 'string'
  const str = typeof value === 'string' ? value : String(value);
  if (Array.from(str).length > def.maxLen) {
    return \`не более \${def.maxLen} символов\`;
  }
  return undefined;
}

export function validateAttributes(
  type: PropertyType,
  attrs: PropertyAttributes,
): AttrErrors {
  const errors: AttrErrors = {};
  const fields = fieldsForType(type);
  const fieldKeys = new Set<string>(fields.map((field) => field.key));

  for (const [rawKey, rawValue] of Object.entries(attrs)) {
    if (!fieldKeys.has(rawKey)) {
      continue;
    }
    if (typeof rawValue !== 'string' && typeof rawValue !== 'number') {
      continue;
    }
    const error = validateField(type, rawKey as AttrKey, rawValue);
    if (error !== undefined) {
      errors[rawKey as AttrKey] = error;
    }
  }

  return errors;
}
`;
}
